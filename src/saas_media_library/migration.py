"""Convert resource policies into ``UploadProfile`` definitions.

``profiles_from_policies`` maps each policy to an equivalent profile;
``render_profiles_module`` writes them as Python source to commit to the app.
``python -m saas_media_library.migrate_policies`` does both for a tenant.
``find_profile`` looks a profile up by the old ``(resource_type,
collection_name)`` pair, as the server resolved policies.
"""

from __future__ import annotations

import copy
import pprint
from typing import Any, Dict, Iterable, List, Mapping, Optional

from saas_media_library.models import ProcessingConfig, ResourcePolicy
from saas_media_library.profiles import UploadProfile

_LINE_WIDTH = 88

_MODULE_HEADER = '''"""Upload profiles converted from resource policies.

Generated by ``python -m saas_media_library.migrate_policies``: review the
rules, then commit this module and upload with
``client.uploads.upload_file(..., profile=UPLOAD_PROFILES[key])``.

Keys are "resource_type/collection_name", or "resource_type" for a policy
without a collection. To look one up by the old pair, use
``saas_media_library.find_profile(UPLOAD_PROFILES, resource_type,
collection_name)``: like the server, it falls back to the resource type's
profile.
"""

from saas_media_library import AssetKind, ProcessingConfig, UploadProfile, Visibility

'''


def policy_key(resource_type: str, collection_name: Optional[str] = None) -> str:
    """``"resource_type/collection_name"``, or ``"resource_type"`` without a collection."""
    return f"{resource_type}/{collection_name}" if collection_name else resource_type


def find_profile(
    profiles: Mapping[str, UploadProfile],
    resource_type: str,
    collection_name: Optional[str] = None,
) -> Optional[UploadProfile]:
    """The profile that replaces the policy the server used for this pair.

    Same resolution as the server's policy lookup: the exact
    ``"resource_type/collection_name"`` profile, else the resource type's
    default (``"resource_type"``, a policy without a collection), else None:
    no policy applied to that pair, so the upload needs a profile of its own.
    """
    if collection_name is not None:
        profile = profiles.get(policy_key(resource_type, collection_name))
        if profile is not None:
            return profile
    return profiles.get(policy_key(resource_type))


def profiles_from_policies(policies: Iterable[ResourcePolicy]) -> Dict[str, UploadProfile]:
    """One ``UploadProfile`` per policy, keyed by ``policy_key``, sorted by key.

    Every rule carries over: kind, visibility, MIME types, size bounds,
    ``allow_multiple``, permissions, ``allow_anonymous`` and the processing
    config exactly as the policy had it (including ``enable_transcription``,
    which a policy defaults to True but a policy-less upload to False).
    Inactive policies are converted too; filter them out beforehand if
    needed. The profile's ``name`` is its key.

    Raises:
        ValueError: if two policies map to the same key, or a policy allows a
            MIME type that is not ``type/subtype``.
    """
    profiles: Dict[str, UploadProfile] = {}
    for policy in policies:
        key = policy_key(policy.resource_type, policy.collection_name)
        if key in profiles:
            raise ValueError(f"More than one resource policy maps to profile key {key!r}")
        try:
            profiles[key] = _profile_from_policy(key, policy)
        except ValueError as exc:
            raise ValueError(f"Resource policy {key!r} cannot be converted: {exc}") from exc
    return dict(sorted(profiles.items()))


def render_profiles_module(profiles: Mapping[str, UploadProfile]) -> str:
    """Python source of a module defining ``UPLOAD_PROFILES = {key: UploadProfile(...)}``.

    Every profile field is written out explicitly, so importing the module
    gives profiles equal to ``profiles``.
    """
    if not profiles:
        return _MODULE_HEADER + "UPLOAD_PROFILES = {}\n"
    lines = ["UPLOAD_PROFILES = {"]
    for key, profile in profiles.items():
        lines.append(f"    {key!r}: UploadProfile(")
        lines.extend(_profile_arguments(profile, indent=" " * 8))
        lines.append("    ),")
    lines.append("}")
    return _MODULE_HEADER + "\n".join(lines) + "\n"


# ── Private helpers ────────────────────────────────────────────────────

def _profile_from_policy(key: str, policy: ResourcePolicy) -> UploadProfile:
    constraints = policy.file_constraints
    permissions = policy.permission_requirements
    config = policy.processing_config
    return UploadProfile(
        name=key,
        kind=policy.kind,
        visibility=policy.visibility,
        allowed_mime_types=set(constraints.allowed_mime_types),
        min_size_bytes=constraints.min_size_bytes,
        max_size_bytes=constraints.max_size_bytes,
        allow_multiple=constraints.allow_multiple,
        required_permissions=set(permissions.required_permissions),
        allow_anonymous=permissions.allow_anonymous,
        # Every field copied: the policy's enable_transcription (a policy
        # defaults to True) must not fall back to the upload default False.
        processing_config=ProcessingConfig(
            step_options=copy.deepcopy(config.step_options),
            use_filename_as_asset_id=config.use_filename_as_asset_id,
            enable_transcription=config.enable_transcription,
        ),
    )


def _profile_arguments(profile: UploadProfile, indent: str) -> List[str]:
    config = profile.processing_config
    lines = [
        _argument(indent, "name", repr(profile.name)),
        _argument(indent, "kind", f"AssetKind.{profile.kind.name}"),
        _argument(indent, "visibility", f"Visibility.{profile.visibility.name}"),
        _argument(indent, "allowed_mime_types", _set_source(profile.allowed_mime_types)),
        _argument(indent, "min_size_bytes", repr(profile.min_size_bytes)),
        _argument(indent, "max_size_bytes", repr(profile.max_size_bytes)),
        _argument(indent, "allow_multiple", repr(profile.allow_multiple)),
        _argument(indent, "required_permissions", _set_source(profile.required_permissions)),
        _argument(indent, "allow_anonymous", repr(profile.allow_anonymous)),
    ]
    if config is None:
        lines.append(_argument(indent, "processing_config", "None"))
        return lines

    inner = indent + " " * 4
    lines.append(f"{indent}processing_config=ProcessingConfig(")
    lines.append(_argument(inner, "step_options", _value_source(config.step_options, inner, "step_options")))
    lines.append(_argument(inner, "use_filename_as_asset_id", repr(config.use_filename_as_asset_id)))
    lines.append(_argument(inner, "enable_transcription", repr(config.enable_transcription)))
    lines.append(f"{indent}),")
    return lines


def _argument(indent: str, name: str, source: str) -> str:
    return f"{indent}{name}={source},"


def _set_source(values: Optional[Iterable[str]]) -> str:
    if values is None:
        return "None"
    values = sorted(values)
    if not values:
        return "set()"
    return "{" + ", ".join(repr(v) for v in values) + "}"


def _value_source(value: Any, indent: str, name: str) -> str:
    """``repr`` of a JSON-like value, wrapped to fit after ``{indent}{name}=``."""
    column = len(indent) + len(name) + 1
    source = pprint.pformat(value, width=max(_LINE_WIDTH - column, 40), sort_dicts=False)
    return source.replace("\n", "\n" + " " * column)
